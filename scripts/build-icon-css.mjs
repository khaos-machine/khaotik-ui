#!/usr/bin/env node
// Regenerates assets/icons/ from @phosphor-icons/web: one stylesheet for the
// regular and fill weights, plus their two woff2 files and Phosphor's licence.
//
// Phosphor's own stylesheets list woff2, woff, ttf and svg in every
// @font-face, so a bundler copies all four into a web build: 7.5 MB for the two
// weights, of which a browser fetches only the 279 KB of woff2. The derived
// sheet names woff2 alone, which every browser this kit targets reads.
//
// `--check` regenerates in memory and exits 1 if assets/icons/ differs, so a
// Phosphor upgrade cannot leave the shipped glyph map behind.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const phosphor = join(root, 'node_modules/@phosphor-icons/web')
const out = join(root, 'assets/icons')
const WEIGHTS = { regular: 'Phosphor', fill: 'Phosphor-Fill' }

const files = {
  'LICENSE-phosphor': readFileSync(join(phosphor, 'LICENSE')),
}
let css = '/* Generated by scripts/build-icon-css.mjs from @phosphor-icons/web. Do not edit. */\n'
for (const [weight, font] of Object.entries(WEIGHTS)) {
  const source = readFileSync(join(phosphor, 'src', weight, 'style.css'), 'utf8')
  const woff2Only = source.replace(/src:[^;]*;/, `src: url("./${font}.woff2") format("woff2");`)
  if (woff2Only === source || /\.(woff|ttf|svg)\b/.test(woff2Only)) {
    console.error(`build-icon-css: ${weight}/style.css no longer has the @font-face src this script rewrites.`)
    process.exit(2)
  }
  css += `\n/* ${weight} */\n${woff2Only}`
  files[`${font}.woff2`] = readFileSync(join(phosphor, 'src', weight, `${font}.woff2`))
}
files['phosphor.css'] = Buffer.from(css)

if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([name, bytes]) => {
    try {
      return !readFileSync(join(out, name)).equals(bytes)
    } catch {
      return true
    }
  })
  if (stale.length) {
    console.error(`build-icon-css: assets/icons/ is stale: ${stale.map(([n]) => n).join(', ')}. Run npm run build-icon-css.`)
    process.exit(1)
  }
  console.log('build-icon-css: assets/icons/ is current')
} else {
  mkdirSync(out, { recursive: true })
  for (const [name, bytes] of Object.entries(files)) writeFileSync(join(out, name), bytes)
  console.log(`build-icon-css: ${Object.keys(files).length} files -> assets/icons/`)
}
