#!/usr/bin/env python3
"""
Generate tokens.css from tokens.json.

    python3 build-tokens.py            write tokens.css
    python3 build-tokens.py --watch    rebuild on every save, until Ctrl-C
    python3 build-tokens.py --check    exit 1 if the file is out of date

── the contract ─────────────────────────────────────────────────────────────
tokens.json is the source of truth for stage 1, Branding. tokens.css is
OUTPUT — editing it directly is a mistake the next build silently reverses, so
the generated file says so in its own header.

Two tiers come out of this:

    primitive   named for what it IS      --indigo-950: #070623
    semantic    named for what it DOES    --surface-base: var(--indigo-950)

Primitives are emitted once. Semantic tokens are emitted twice, once per mode,
and only ever as references — so a colour exists in exactly one place and
changing it is one edit rather than a search.

── selectors, and why they are these ────────────────────────────────────────
Dark is the default and lands on `:root, .dark, [data-theme="dark"]`. The two
extra hooks are aliases carried over from the previous theme so existing markup
keeps working.

Light lands on `html[data-theme="light"]` — specificity (0,1,1), deliberately
one notch above `:root` (0,1,0). Ordering alone would not be enough, because
the compatibility block also matches `:root`; winning on specificity makes the
light block order-independent.

`{token}` in a value becomes `var(--token)`, and `{color.navy.950}` becomes
`var(--indigo-950)`. A reference to a name that does not exist is a build error
rather than a CSS variable that silently resolves to nothing.
"""
import json
import pathlib
import re
import sys
import time

# everything touched is relative to the repo root; this file lives in tokens/
ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tokens" / "tokens.json"
OUT = ROOT / "tokens" / "tokens.css"

BANNER = """/* ═══════════════════════════════════════════════════════════════════════════
   KHAOTIK — DESIGN TOKENS
   ───────────────────────────────────────────────────────────────────────────
   GENERATED FROM tokens.json BY build-tokens.py — DO NOT EDIT THIS FILE.
   Edit tokens.json and re-run:  python3 build-tokens.py

   Two tiers:
     primitive   named for what it IS     a hex, defined once
     semantic    named for what it DOES   var(--that-primitive)

   Every colour is defined exactly once, in the primitive block. Semantic
   tokens only ever reference it, so changing a value is a single edit —
   change the primitive and everything pointing at it follows.
   ═══════════════════════════════════════════════════════════════════════════ */
"""


def var_name(path):
    """color.indigo.950 -> --indigo-950 · space.md -> --spacing-md · plain -> --plain"""
    if path.startswith("color."):
        return "--" + "-".join(path.split(".")[1:])
    if path.startswith("space."):
        return "--spacing-" + path.split(".", 1)[1]
    if path.startswith(("radius.", "size.", "font.")):
        head, rest = path.split(".", 1)
        return f"--{head}-{rest}"
    return "--" + path.replace(".", "-")


def resolve(value, known):
    """Turn {a.b.c} references into var(--a-b-c), failing loudly on typos."""
    def sub(m):
        name = var_name(m.group(1))
        if name not in known:
            raise TokenError(
                f"tokens.json references {{{m.group(1)}}}, which resolves to {name}, "
                f"but no token by that name is defined"
            )
        return f"var({name})"
    return re.sub(r"\{([a-z0-9.\-]+)\}", sub, str(value))


def comment(desc, indent="  "):
    if not desc:
        return []
    lines = desc if isinstance(desc, list) else [desc]
    if len(lines) == 1:
        return [f"{indent}/* {lines[0]} */"]
    out = [f"{indent}/* {lines[0]}"]
    out += [f"{indent}   {l}".rstrip() for l in lines[1:]]
    out[-1] += " */"
    return out


class TokenError(Exception):
    """A problem in tokens.json. Carries a message fit to show and move on."""


def render():
    """tokens.json -> (css, summary). Raises TokenError; never exits."""
    try:
        doc = json.loads(SRC.read_text())
    except FileNotFoundError:
        raise TokenError(f"{SRC.name} is missing")
    except json.JSONDecodeError as e:
        # by far the most common case while watching: a half-typed edit
        raise TokenError(f"{SRC.name} is not valid JSON — line {e.lineno}, column {e.colno}: {e.msg}")
    try:
        prim, sem, compat, derived = (doc["primitive"], doc["semantic"],
                                      doc["compat"], doc["derived"])
    except KeyError as e:
        raise TokenError(f"{SRC.name} has no top-level {e} block")

    # ── every name that will exist, so references can be validated ──────────
    known = set()
    for fam, steps in prim["color"].items():
        known |= {f"--{fam}-{s}" for s in steps if not s.startswith("$")}
    for group in ("space", "radius", "size", "font"):
        known |= {var_name(f"{group}.{k}") for k in prim[group] if not k.startswith("$")}
    for style, parts in prim["type"].items():
        if style.startswith("$"):
            continue
        known |= {f"--{style}-{p}" for p in parts}
    known |= {f"--{k}" for k in sem["dark"] if not k.startswith("$")}
    known |= {f"--{k}" for k in compat["alias"]}
    known |= {f"--{k}" for k in compat["dark"] if not k.startswith("$")}
    known |= {f"--{k}" for k in derived if not k.startswith("$")}

    L = [BANNER]

    # ── primitives ──────────────────────────────────────────────────────────
    L.append(":root{")
    L += comment(prim.get("$description"))
    for fam, steps in prim["color"].items():
        L.append("")
        L.append(f"  /* {fam} */")
        # A family may carry its own $description — why a hue moved, why a rung
        # has no consumer left. It rides through as a comment rather than being
        # dropped, so the generated file explains itself as well as the source.
        L += comment(steps.get("$description"))
        for step, hexv in steps.items():
            if step.startswith("$"):
                continue
            L.append(f"  --{fam}-{step}:{hexv};")
    L.append("")
    L.append("  /* space · radius · size · font — mode-invariant */")
    for group in ("space", "radius", "size", "font"):
        for k, v in prim[group].items():
            if k.startswith("$"):
                continue
            L.append(f"  {var_name(f'{group}.{k}')}:{v};")
    L.append("")
    L += comment(prim["type"].get("$description"))
    for style, parts in prim["type"].items():
        if style.startswith("$"):
            continue
        L.append("  " + " ".join(f"--{style}-{p}:{v};" for p, v in parts.items()))
    L.append("}")

    # ── semantic, dark ──────────────────────────────────────────────────────
    L.append("")
    L += comment(sem.get("$description"), indent="")
    L.append(':root,\n.dark,\n[data-theme="dark"]{')
    for k, v in sem["dark"].items():
        if k.startswith("$"):
            continue
        L.append(f"  --{k}:{resolve(v, known)};")
    L.append("")
    L += comment(compat.get("$description"))
    for k, v in compat["alias"].items():
        L.append(f"  --{k}:{resolve(v, known)};")
    for k, v in compat["dark"].items():
        if k.startswith("$"):
            continue
        L.append(f"  --{k}:{resolve(v, known)};")
    L.append("}")

    # ── semantic, light ─────────────────────────────────────────────────────
    L.append("")
    L.append("/* Light. html[data-theme=\"light\"] is (0,1,1) — one notch above :root,")
    L.append("   so this block wins on specificity rather than on source order. */")
    L.append('html[data-theme="light"]{')
    for k, v in sem["light"].items():
        if k.startswith("$"):
            continue
        L.append(f"  --{k}:{resolve(v, known)};")
    for k, v in compat["light"].items():
        if k.startswith("$"):
            continue
        L.append(f"  --{k}:{resolve(v, known)};")
    L.append("}")

    # ── derived ─────────────────────────────────────────────────────────────
    L.append("")
    L += comment(derived.get("$description"), indent="")
    L.append(":root{")
    for k, v in derived.items():
        if k.startswith("$"):
            continue
        L.append(f"  --{k}:{resolve(v, known)};")
    L.append("}")

    n_prim = sum(len([k for k in s if not k.startswith("$")])
                 for s in prim["color"].values())
    n_sem = len([k for k in sem["dark"] if not k.startswith("$")])
    summary = f"{n_prim} primitive colours, {n_sem} semantic tokens x 2 modes"
    return "\n".join(L) + "\n", summary


def build():
    css, summary = render()
    OUT.write_text(css)
    return summary


def watch():
    """Rebuild whenever tokens.json changes, until Ctrl-C.

    Polling rather than an OS watcher because that needs a dependency and this
    is one small file. 300ms is well under the time it takes to alt-tab to the
    browser, so a save is always finished rebuilding before you look at it.

    A bad edit must NOT stop the watcher — a half-typed value is the normal
    state of a file you are editing. Errors print and the loop keeps going, so
    fixing the typo brings it straight back.
    """
    print(f"watching {SRC.name} — edit it and the CSS follows. Ctrl-C to stop.\n", flush=True)
    last, broken = None, False
    while True:
        try:
            stamp = SRC.stat().st_mtime
        except FileNotFoundError:
            stamp = None
        if stamp != last:
            last = stamp
            clock = time.strftime("%H:%M:%S")
            try:
                print(f"  {clock}  {build()}", flush=True)
                if broken:
                    print(f"           recovered — {OUT.name} is good again", flush=True)
                broken = False
            except TokenError as e:
                print(f"  {clock}  ✗ {e}", flush=True)
                print(f"           {OUT.name} left untouched; fix and save again", flush=True)
                broken = True
        time.sleep(0.3)


def main():
    if "--watch" in sys.argv:
        try:
            watch()
        except KeyboardInterrupt:
            print("\nstopped watching")
        return

    try:
        css, summary = render()
    except TokenError as e:
        sys.exit(f"error: {e}")

    if "--check" in sys.argv:
        if not OUT.exists():
            sys.exit(f"error: {OUT.name} does not exist. Run: python3 build-tokens.py")
        if OUT.read_text() != css:
            sys.exit(
                f"error: {OUT.name} is out of date with {SRC.name}.\n"
                f"Regenerate with: python3 build-tokens.py"
            )
        print(f"{OUT.name} is up to date with {SRC.name}")
        return

    OUT.write_text(css)
    print(f"wrote {OUT.name} — {summary}")


if __name__ == "__main__":
    main()
